import {expect,test} from "@playwright/test";
const base="/shuomi/#/workbench";
test("account switching confirms staged member and organization selection with isolated context",async({page})=>{
 await page.goto(base+"/account");
 const avatar=page.getByRole("button",{name:"linchen_demo账户"});
 await avatar.click();
 const menu=page.getByRole("dialog",{name:"账户快捷操作"});
 await expect(menu).toContainText("admin@example.com");
 await expect(menu).toContainText("武汉硕米电子商务有限公司");
 await expect(menu).not.toContainText("user@sumi.ai");
 await menu.getByRole("button",{name:"切换账户与企业组织"}).click();
 const switcher=page.getByRole("dialog",{name:"切换账户与企业组织"});
 await expect(switcher).toBeVisible();
 await expect(switcher).toContainText("当前身份");
 await expect(switcher).toContainText("模拟同事01");
 const memberSearch=switcher.getByRole("searchbox",{name:"搜索成员"});
 await memberSearch.fill("colleague01@example.test");
 await expect(switcher.getByRole("button",{name:/模拟同事01/})).toBeVisible();
 await expect(switcher.getByRole("button",{name:/模拟同事02/})).toHaveCount(0);
 await memberSearch.fill("不匹配的名字");
 await expect(switcher).toContainText("未找到匹配的成员");
 await switcher.getByRole("button",{name:"清空搜索"}).click();
 await expect(memberSearch).toHaveValue("");
 await switcher.getByRole("button",{name:/模拟同事01/}).click();
 await expect(switcher.getByRole("button",{name:/模拟同事01/})).toHaveAttribute("aria-pressed","true");
 await switcher.getByRole("button",{name:"取消"}).click();
 await expect(page.getByRole("button",{name:"linchen_demo账户"})).toBeVisible();
 await avatar.click();
 await menu.getByRole("button",{name:"切换账户与企业组织"}).click();
 await switcher.getByRole("button",{name:/模拟同事01/}).click();
 await switcher.getByRole("button",{name:"确认切换"}).click();
 await expect(page.getByRole("button",{name:"模拟同事01账户"})).toBeVisible();
 await page.goto(base+"/account/organization/roles");
 await expect(page.getByRole("status")).toContainText("没有该页面的访问权限");
 await page.getByRole("button",{name:"返回管理员"}).click();
 await expect(page.getByRole("button",{name:"linchen_demo账户"})).toBeVisible();
 await page.getByRole("button",{name:"linchen_demo账户"}).click();
 await menu.getByRole("button",{name:"切换账户与企业组织"}).click();
 await switcher.getByRole("searchbox",{name:"搜索成员"}).fill("模拟同事");
 await switcher.getByRole("tab",{name:"切换企业"}).click();
 const organizationSearch=switcher.getByRole("searchbox",{name:"搜索企业"});
 await expect(organizationSearch).toHaveValue("");
 await organizationSearch.fill("不存在的企业");
 await expect(switcher).toContainText("未找到匹配的企业");
 await switcher.getByRole("button",{name:"清空搜索"}).click();
 await expect(switcher.getByText("新增模拟企业")).toHaveCount(0);
 await expect(switcher.getByRole("button",{name:"添加企业"})).toHaveCount(0);
 await organizationSearch.fill("武汉硕米");
 await expect(switcher.getByRole("button",{name:/武汉硕米电子商务有限公司/})).toBeVisible();
 await expect(switcher).toContainText("仅显示已关联企业");
 await switcher.getByRole("tab",{name:"切换成员"}).click();
 await expect(switcher.getByRole("searchbox",{name:"搜索成员"})).toHaveValue("");
 await switcher.getByRole("button",{name:"取消"}).click();
 await expect(page.getByRole("button",{name:"linchen_demo账户"})).toBeVisible();
});
