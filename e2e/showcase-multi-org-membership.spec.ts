import {expect,test} from "@playwright/test";
const base="/shuomi/#/workbench";
const openSwitch=async(page:import("@playwright/test").Page)=>{
 await page.getByRole("button",{name:/账户$/}).click();
 await page.getByRole("dialog",{name:"账户快捷操作"}).getByRole("button",{name:"切换账户与企业组织"}).click();
 return page.getByRole("dialog",{name:"切换账户与企业组织"});
};
test("colleague01 has separate roles in three linked enterprises and no cross-tenant data leakage",async({page})=>{
 await page.goto(base+"/account");
 let dialog=await openSwitch(page);
 await dialog.getByRole("button",{name:/模拟同事01/}).click();
 await dialog.getByRole("button",{name:"确认切换"}).click();
 await expect(page.getByRole("button",{name:"模拟同事01账户"})).toBeVisible();
 dialog=await openSwitch(page);
 await dialog.getByRole("tab",{name:"切换企业"}).click();
 await expect(dialog).toContainText("模拟企业A（运营公司）");
 await expect(dialog).toContainText("模拟企业B（供应链公司）");
 await dialog.getByRole("searchbox",{name:"搜索企业"}).fill("模拟企业A");
 await dialog.getByRole("button",{name:/模拟企业A/}).click();
 await dialog.getByRole("button",{name:"确认切换"}).click();
 await expect(page.getByRole("status")).toContainText("模拟企业A（运营公司）");
 await expect(page.getByRole("status")).toContainText("模拟同事01 · 管理员");
 await expect(page.getByRole("status")).not.toContainText("¥336");
 dialog=await openSwitch(page);
 await expect(dialog).toContainText("模拟同事01");
 await expect(dialog).toContainText("管理员");
 await dialog.getByRole("tab",{name:"切换企业"}).click();
 await dialog.getByRole("searchbox",{name:"搜索企业"}).fill("模拟企业B");
 await dialog.getByRole("button",{name:/模拟企业B/}).click();
 await dialog.getByRole("button",{name:"确认切换"}).click();
 await expect(page.getByRole("status")).toContainText("模拟企业B（供应链公司）");
 await expect(page.getByRole("status")).toContainText("模拟同事01 · 子账号");
 await page.reload();
 await expect(page.getByRole("status")).toContainText("模拟同事01 · 子账号");
 dialog=await openSwitch(page);
 await dialog.getByRole("tab",{name:"切换企业"}).click();
 await dialog.getByRole("button",{name:/武汉硕米电子商务有限公司/}).click();
 await dialog.getByRole("button",{name:"确认切换"}).click();
 await expect(page.getByRole("button",{name:"模拟同事01账户"})).toBeVisible();
 await page.goto(base+"/account/organization/roles");
 await expect(page.getByRole("status")).toContainText("没有该页面的访问权限");
});
