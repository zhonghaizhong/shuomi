import {expect,test} from "@playwright/test";
const base="/shuomi/#/workbench/account";
test("phone and email invitations remain pending until demo acceptance",async({page})=>{
 await page.goto(base+"/organization/members");
 const section=page.getByRole("region",{name:"成员列表"});
 await page.getByRole("button",{name:"邀请成员"}).click();
 const invite=page.getByRole("dialog",{name:"邀请成员"});
 await invite.getByRole("button",{name:"确认邀请"}).click();
 await expect(invite.getByRole("alert")).toContainText("手机号或邮箱");
 await invite.getByRole("textbox",{name:"成员邮箱"}).fill("colleague04@example.test");
 await invite.getByRole("button",{name:"确认邀请"}).click();
 const row=section.getByRole("row").filter({hasText:"colleague04@example.test"});
 await expect(row).toContainText("邀请中");
 await expect(page.getByText("等待成员接受",{exact:true})).toBeVisible();
 await page.reload();
 const persisted=page.getByRole("row").filter({hasText:"colleague04@example.test"});
 await expect(persisted).toContainText("邀请中");
 await page.getByRole("button",{name:"邀请成员"}).click();
 const duplicate=page.getByRole("dialog",{name:"邀请成员"});
 await duplicate.getByRole("textbox",{name:"成员邮箱"}).fill("colleague04@example.test");
 await duplicate.getByRole("button",{name:"确认邀请"}).click();
 await expect(duplicate.getByRole("alert")).toContainText("邮箱已属于");
 await duplicate.getByRole("button",{name:"关闭弹窗"}).click();
 await persisted.getByRole("button",{name:"模拟接受"}).click();
 await expect(persisted).toContainText("正常");
 await page.getByRole("button",{name:"邀请成员"}).click();
 const phoneInvite=page.getByRole("dialog",{name:"邀请成员"});
 await phoneInvite.getByRole("textbox",{name:"成员手机号"}).fill("+8613800138000");
 await phoneInvite.getByRole("button",{name:"确认邀请"}).click();
 const phoneRow=page.getByRole("row").filter({hasText:"+8613800138000"});
 await expect(phoneRow).toContainText("邀请中");
 await expect(phoneRow).toContainText("—");
 await phoneRow.getByRole("button",{name:"取消邀请"}).click();
 await expect(page.getByRole("row").filter({hasText:"+8613800138000"})).toHaveCount(0);
});
