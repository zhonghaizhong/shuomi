import {expect,test} from "@playwright/test";
const base="/shuomi/#/workbench/account";
test("member invitation uses account and email and only activates after acceptance",async({page})=>{
 await page.goto(base+"/organization/members");
 const section=page.getByRole("region",{name:"成员列表"});
 await expect(page.getByText("邀请中",{exact:true}).first()).toBeVisible();
 const initial=section.getByText("共 4 位成员");
 await expect(initial).toBeVisible();
 await page.getByRole("button",{name:"邀请成员"}).click();
 const invite=page.getByRole("dialog",{name:"邀请成员"});
 await invite.getByRole("textbox",{name:"成员账号"}).fill("colleague04");
 await invite.getByRole("textbox",{name:"成员邮箱"}).fill("colleague04@example.test");
 await invite.getByRole("button",{name:"确认邀请"}).click();
 const row=section.getByRole("row").filter({hasText:"colleague04"});
 await expect(row).toContainText("邀请中");
 await expect(section).toContainText("共 5 位成员");
 await expect(page.getByText("等待成员接受",{exact:true})).toBeVisible();
 await page.reload();
 const persisted=page.getByRole("row").filter({hasText:"colleague04"});
 await expect(persisted).toContainText("邀请中");
 await page.getByRole("button",{name:"邀请成员"}).click();
 const duplicate=page.getByRole("dialog",{name:"邀请成员"});
 await duplicate.getByRole("textbox",{name:"成员账号"}).fill("colleague04");
 await duplicate.getByRole("textbox",{name:"成员邮箱"}).fill("another04@example.test");
 await duplicate.getByRole("button",{name:"确认邀请"}).click();
 await expect(duplicate.getByRole("alert")).toContainText("账号已存在");
 await duplicate.getByRole("button",{name:"关闭弹窗"}).click();
 await persisted.getByRole("button",{name:"模拟接受"}).click();
 await expect(persisted).toContainText("正常");
 await page.getByRole("button",{name:"邀请成员"}).click();
 const next=page.getByRole("dialog",{name:"邀请成员"});
 await next.getByRole("textbox",{name:"成员账号"}).fill("colleague05");
 await next.getByRole("textbox",{name:"成员邮箱"}).fill("colleague05@example.test");
 await next.getByRole("button",{name:"确认邀请"}).click();
 const pending=page.getByRole("row").filter({hasText:"colleague05"});
 await expect(pending).toContainText("邀请中");
 await pending.getByRole("button",{name:"取消邀请"}).click();
 await expect(page.getByRole("row").filter({hasText:"colleague05"})).toHaveCount(0);
});
